// V1 Coaching Integration Boundary: the iOS fixtures are a contract. They are regenerated here and must equal the committed files byte for byte; every
// file's declared state is the state its response shows; every server-produced client state has an example; no fixture holds real data.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {ROOT} from './v1cib-helpers.mjs';

const dir=path.join(ROOT,'CoachingCore/fixtures/v1cib-ios');
const {buildFixtures}=await import(pathToFileURL(path.join(ROOT,'CoachingCore/scripts/v1cib-ios-fixtures.mjs')).href);
const {V1_SERVER_STATES}=await import(pathToFileURL(path.join(ROOT,'CoachingCore/src/boundary/views.mjs')).href);

test('V1CIB iOS fixtures: regenerated byte for byte, each declared state is the state its response shows, and every server state has an example',()=>{
 const built=buildFixtures(),names=Object.keys(built).sort(),onDisk=fs.readdirSync(dir).filter(f=>f.endsWith('.json')).map(f=>f.slice(0,-5)).sort();
 assert.deepEqual(onDisk,names,'the same files');
 for(const name of names){
  const text=JSON.stringify(built[name],null,1)+'\n';assert.equal(fs.readFileSync(path.join(dir,`${name}.json`),'utf8'),text,name+': committed bytes equal the regenerated ones');
  if(name==='00-index')continue;const r=built[name].response,got=r?.view?.state??r?.state??null;if(got)assert.equal(got,built[name].state,name);
 }
 const states=new Set(Object.values(built).map(f=>f.state).filter(Boolean));
 // V1 Final Closure: every state the V1 server produces has an example (REDUCED belongs to the temporary reduction, which V1 does not offer).
 for(const s of V1_SERVER_STATES)assert.ok(states.has(s),'an example of '+s);assert.ok(!states.has('REDUCED'));
 assert.equal(built['00-index'].synthetic,true);
 const all=JSON.stringify(built);for(const w of ['@','cpf','+55'])assert.ok(!all.toLowerCase().includes(w),'no personal identifier ('+w+')');
});
