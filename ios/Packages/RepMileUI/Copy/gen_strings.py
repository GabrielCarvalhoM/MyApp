#!/usr/bin/env python3
"""Generate Resources/<lang>.lproj/Localizable.strings from copy.psv (key, pt-BR, en, es). Run: python3 -I Copy/gen_strings.py (package root)."""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for n, line in enumerate(open(os.path.join(root, "Copy", "copy.psv"), encoding="utf-8"), 1):
    line = line.rstrip("\n")
    if not line or line.startswith("#"): continue
    parts = line.split("|")
    if len(parts) != 4: sys.exit(f"copy.psv:{n}: expected 4 columns, got {len(parts)}")
    rows.append(parts)
keys = [r[0] for r in rows]
dup = {k for k in keys if keys.count(k) > 1}
if dup: sys.exit(f"duplicate keys: {sorted(dup)}")
esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
# PENDING_TRANSLATION in the en or es column: no translation from a source yet (e.g. copy that exists only in pt-BR in the Figma). That
# locale ships the pt-BR text, never a translation invented here, and the key is listed in Copy/PENDING_TRANSLATION.txt (audit list).
PENDING = "PENDING_TRANSLATION"
bad = [r[0] for r in rows if r[1] == PENDING]
if bad: sys.exit(f"pt-BR is the source and cannot be {PENDING}: {bad}")
pending = []
for i, lang in enumerate(["pt-BR", "en", "es"], 1):
    d = os.path.join(root, "Sources", "RepMileUI", "Resources", f"{lang}.lproj"); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write("/* Generated from Copy/copy.psv by Copy/gen_strings.py. Do not edit. */\n")
        for r in rows:
            value = r[i]
            if value == PENDING: value = r[1]; pending.append((r[0], lang))
            f.write(f'"{esc(r[0])}" = "{esc(value)}";\n')
with open(os.path.join(root, "Copy", "PENDING_TRANSLATION.txt"), "w", encoding="utf-8") as f:
    f.write("# Generated by Copy/gen_strings.py: key|locale whose copy.psv column is PENDING_TRANSLATION (that locale shows the pt-BR text).\n")
    for k, lang in pending: f.write(f"{k}|{lang}\n")
print(f"{len(rows)} keys x 3 languages; {len(pending)} key-locales pending translation (Copy/PENDING_TRANSLATION.txt)")
