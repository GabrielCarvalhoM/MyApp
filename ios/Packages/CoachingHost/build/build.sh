#!/bin/sh
# RepMile CoachingHost (front A): the production bundle and its proofs, from the repository root. Adapted from the HR5R native build
# (audits/v1-hr5-runna-parity-2026-11-25/native/build.sh): here the linker copy (build/link.mjs) writes only into this package, so no redirect
# preload is needed. Steps: link the facade entry (50 modules, 18 assets, export gate), check the manifest against
# the amendment in force, REPMILE-COACHINGCORE-V1-CCP79-AMENDMENT-3 (build/check-manifest.mjs), pin the bundle sha into Swift (BundlePin.swift: verified at boot),
# check the equivalence fixtures are the HR5R copies byte for byte, and reproduce the shared fixtures through the facade (facade-calls.json).
# Deterministic: `build.sh --twice` fails if a second run changes anything tracked.
set -eu
cd "$(git rev-parse --show-toplevel)"
P=ios/Packages/CoachingHost
node $P/build/link.mjs
node $P/build/check-manifest.mjs > /dev/null || { node $P/build/check-manifest.mjs; exit 1; }
R=$P/Sources/CoachingHost/Resources
B=$(shasum -a 256 $R/coachinghost.js | cut -d' ' -f1); M=$(shasum -a 256 $R/assets-manifest.json | cut -d' ' -f1)
cat > $P/Sources/CoachingHost/BundlePin.swift <<SWIFT
// Generated by build/build.sh; do not edit. The production bundle this module ships, verified before the bundle is evaluated (A handoff §7.1).
enum BundlePin {
    static let bundleSha256 = "$B"
    static let assetsManifestSha256 = "$M"
}
SWIFT
H=audits/v1-hr5-runna-parity-2026-11-25/native/ios/Tests/P0HostTests/Fixtures
for f in core int final hr5 hmac; do cmp -s $H/$f.json $P/Tests/CoachingHostTests/Fixtures/$f.json || { echo "build.sh: $f.json is not the HR5R copy" >&2; exit 1; }; done
node $P/facade/test/reproduce-fixtures.mjs
[ "${1:-}" = "--twice" ] && { git diff --quiet -- $P || { echo "build.sh: not deterministic" >&2; git diff --stat -- $P >&2; exit 1; }; }
echo "build.sh: bundle $B; manifest checked; fixtures reproduced"
