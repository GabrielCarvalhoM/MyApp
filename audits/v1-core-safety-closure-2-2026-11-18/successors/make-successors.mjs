// Core Safety & Lifecycle closure-2: builds the successor tests (SSCTR C-C1, QRE-CORE-R2-02) from the historical tests' own source.
// A successor is the historical test, unchanged except for the substitutions declared in successors*.json: each one must occur exactly once
// in that test's body, and nothing else is removed. The historical files are only read. Every file-level helper of the historical file is
// kept, so the scenario is the same code. Usage (from the repository root): node audits/v1-core-safety-closure-2-2026-11-18/successors/make-successors.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const only=(process.argv.find(a=>a.startsWith('--only='))??'').slice(7)||null;
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../../..'),spec={files:Object.assign({},...fs.readdirSync(here).filter(f=>/^successors[^/]*[.]json$/.test(f)).filter(f=>!only||f===only).sort().map(f=>JSON.parse(fs.readFileSync(path.join(here,f),'utf8')).files))};
const check=process.argv.includes('--check'),sha=s=>createHash('sha256').update(s).digest('hex');
/**
 * The top-level test blocks of a file: from a line starting `test(` (or a top-level `for(…)test(` loop that registers one test per item) to
 * the first later line that is exactly `});`.
 */
const opens=l=>l.startsWith('test(')||/^for\(.*\)test\(/.test(l);
function blocks(lines){const out=[];for(let i=0;i<lines.length;i++)if(opens(lines[i])){let j=i+1;while(j<lines.length&&lines[j]!=='});')j++;if(j>=lines.length)throw new Error('unclosed test at line '+(i+1));out.push({start:i,end:j,title:lines[i]});i=j;}return out;}
const ledger=[];let failed=false;
for(const [target,entry] of Object.entries(spec.files)){
 const srcPath=path.join(root,'CoachingCore/test',entry.historical),src=fs.readFileSync(srcPath,'utf8'),eol=src.includes('\r\n')?'\r\n':'\n',lines=src.split(/\r?\n/),bs=blocks(lines);
 const keep=lines.map(()=>true);for(const b of bs)for(let k=b.start;k<=b.end;k++)keep[k]=false;
 const body=[`// GENERATED by audits/v1-core-safety-closure-2-2026-11-18/successors/make-successors.mjs from test/${entry.historical} (sha256 ${sha(src)}).`,
  `// Core Safety & Lifecycle closure-2 successor tests (SSCTR C-C1 / QRE-CORE-R2-02). The historical file is unedited; each test below is its`,
  `// historical test with only the substitutions listed in successors*.json (each matched exactly once). Do not edit by hand.`];
 lines.forEach((l,k)=>{if(keep[k])body.push(l);});
 // Declared additions after the historical helpers (the as-if controls a successor compares with): never a change to a helper.
 if(entry.prelude?.length)body.push("","// ---------- closure-2 successor additions (successors*.json prelude) ----------",...entry.prelude);
 for(const t of entry.tests){
  // `title` is matched as written in the source (escapes included), right after the test's opening quote.
  const b=bs.filter(x=>x.title.includes("test('"+t.title)||x.title.includes('test(`'+t.title));if(b.length!==1){console.error(`${entry.historical}: ${b.length} tests match «${t.title}»`);failed=true;continue;}
  let text=lines.slice(b[0].start,b[0].end+1).join('\n');
  const q=text.indexOf('test(')+'test('.length+1;text=text.slice(0,q)+'SUCCESSOR closure-2 · '+text.slice(q);
  for(const [from,to] of t.substitutions??[]){const n=text.split(from).length-1;if(n!==1){console.error(`${entry.historical} «${t.title}»: substitution matched ${n} times: ${from.slice(0,120)}`);failed=true;continue;}text=text.replace(from,()=>to);}
  if(t.append?.length){const lines2=text.split('\n');lines2.splice(lines2.length-1,0,...t.append);text=lines2.join('\n');}
  body.push('',text);
  ledger.push({historical:`${entry.historical}:${b[0].start+1}`,title:t.title,successor:target,substitutions:(t.substitutions??[]).length,appended:(t.append??[]).length,why:t.why});
 }
 const out=body.join(eol)+eol,outPath=path.join(root,'CoachingCore/test',target);
 if(check){if(!fs.existsSync(outPath)||fs.readFileSync(outPath,'utf8')!==out){console.error('stale: '+target);failed=true;}}
 else fs.writeFileSync(outPath,out);
}
if(!check&&!only)fs.writeFileSync(path.join(here,'SUCCESSOR_LEDGER.json'),JSON.stringify({generatedBy:'make-successors.mjs',entries:ledger},null,1)+'\n');
if(failed){console.error('FAILED');process.exit(1);}
console.log(`${check?'checked':'wrote'} ${Object.keys(spec.files).length} files, ${ledger.length} successor tests`);
